package com.volunteerhub.security;

import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.springframework.security.web.csrf.CsrfToken;
import org.springframework.web.filter.OncePerRequestFilter;

import java.io.IOException;

/**
 * Filter that forces resolution of the deferred CSRF token so that the XSRF-TOKEN cookie
 * is sent to Single Page Applications (SPAs) and JavaScript clients.
 */
public class CsrfCookieFilter extends OncePerRequestFilter {

    @Override
    protected void doFilterInternal(HttpServletRequest request,
                                    HttpServletResponse response,
                                    FilterChain filterChain) throws ServletException, IOException {
        CsrfToken csrfToken = (CsrfToken) request.getAttribute(CsrfToken.class.getName());
        if (csrfToken != null) {
            // Invoking getToken() forces evaluation of the deferred token and triggers Set-Cookie
            csrfToken.getToken();
        }
        filterChain.doFilter(request, response);
    }
}
